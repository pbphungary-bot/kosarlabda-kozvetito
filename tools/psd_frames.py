#!/usr/bin/env python3
"""Splits the baked backgrounds into (a) 'statics.png' – the fixed layers of the PSD WITHOUT the court and the panel shape – and
(b) the numbers needed to draw the panel as a resizable shape (graphics/js/frames.js): panel box, corner radius, stroke width + colour,
layer opacity and the placement of the court picture. The court itself is saved once as graphics/assets/court/court.jpg (embedded smart object).
Usage: python3 tools/psd_frames.py            (read-only on the PSDs; needs psd-tools, numpy, pillow)"""
import io, json, os, sys, warnings
warnings.filterwarnings('ignore')
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import psd_extract as X
from psd_tools import PSDImage
from PIL import Image, ImageFilter

ROOT = X.ROOT
OUT = os.path.join(X.OUT, 'templates')
COURT = 'Háttér nb1a - kosárpályával'


def hex_of(c):
    return '#%02x%02x%02x' % tuple(round(c[k]) for k in (b'Rd  ', b'Grn ', b'Bl  '))


def main(only=None):
    frames, saved_court = {}, False
    for tid, (fname, opts) in X.TEMPLATES.items():
        if only and tid not in only:
            continue
        psd = PSDImage.open(os.path.join(X.SRC, fname))
        layers = [l for l in psd.descendants() if not l.is_group()]
        court = next((l for l in layers if l.name == COURT), None)
        panel = next((l for l in layers if l.kind == 'shape' and l.name in ('TOP', 'Téglalap 1')), None)
        if not court or not panel:
            print('skip', tid, '(no court / panel layer)'); continue
        if not saved_court:
            Image.open(io.BytesIO(court.smart_object.data)).convert('RGB').save(os.path.join(X.OUT, 'assets', 'court', 'court.jpg'), quality=92, optimize=True)
            saved_court = True
        st = panel.stroke
        o = panel.origination[0]._data
        frames[tid] = {
            'box': [int(v) for v in panel.bbox], 'r': round(o[b'keyOriginRRectRadii'][b'topLeft']), 'sw': st.line_width,
            'stroke': hex_of(st.content[b'Clr ']), 'opacity': round(panel.opacity / 255, 4), 'court': [int(v) for v in court.bbox],
        }
        # the vector bbox is the stroke's centre line: measure the real outer edge of the border in the baked background (alpha bbox around the shape)
        old = Image.open(os.path.join(OUT, tid, 'background.png')).convert('RGBA').split()[3]
        x0, y0, x1, y1 = frames[tid]['box']
        import numpy as np
        A = np.asarray(old) > 128
        mx, my = (x0 + x1) // 2, (y0 + y1) // 2
        cx = x0 + 60  # a column near the left end: free of the logo strip below the panel
        col = np.where(A[max(0, y0 - 14):y1 + 14, cx])[0] + max(0, y0 - 14)
        row = np.where(A[my, max(0, x0 - 14):x1 + 14])[0] + max(0, x0 - 14)
        frames[tid]['box'] = [int(row.min()), int(col.min()), int(row.max()) + 1, int(col.max()) + 1]
        keep = [l for l in layers if X.is_static(l, opts) and l is not panel and l is not court]
        keep_ids = {id(l) for l in keep}
        for l in layers:
            l.visible = id(l) in keep_ids
        for g in psd.descendants():
            if g.is_group():
                g.visible = True
        im = psd.composite(force=True)
        cover = Image.new('RGBA', (psd.width, psd.height), (0, 0, 0, 0))
        cover.alpha_composite(im.convert('RGBA'))
        mask = cover.split()[3].point(lambda v: 255 if v > 0 else 0)
        pbp = next((l for l in layers if l.name == 'pbp_logo'), None)
        if pbp is not None:  # the MKOSZ logo that replaced the Play-by-Play one in the baked background
            hb = next(l for l in layers if l.name.startswith('74641_HUNBASKET')); tp = next(l for l in layers if l.name.startswith('tippmix'))
            mk = Image.open(X.MKOSZ_ASSET).convert('RGBA')
            mx, my = tp.bbox[2] + X.MKOSZ_GAP, round((hb.bbox[1] + hb.bbox[3]) / 2 - mk.height / 2)
            mask.paste(255, (mx - 2, my - 2, mx + mk.width + 2, my + mk.height + 2))
        mask = mask.filter(ImageFilter.MaxFilter(5))  # +2 px: anti-aliased edges
        # the pixels come from the baked background (Photoshop's own composite: exact text / logo rendering), only where a fixed layer is
        oldfull = Image.open(os.path.join(OUT, tid, 'background.png')).convert('RGBA')
        full = Image.new('RGBA', oldfull.size, (0, 0, 0, 0))
        full.paste(oldfull, (0, 0), mask)
        d = os.path.join(OUT, tid); os.makedirs(d, exist_ok=True)
        full.save(os.path.join(d, 'statics.png'), optimize=True)
        print('ok', tid, frames[tid], [l.name[:20] for l in keep])
    js = '// Generated by tools/psd_frames.py – the panels (frames) of the PSD graphics as resizable shapes.\n// box = [x0, y0, x1, y1] of the shape, court = placement of the court picture [x0, y0, x1, y1], sw / r in px.\nexport const FRAMES = ' + json.dumps(frames, indent=1, ensure_ascii=False) + ';\n'
    if not only:
        open(os.path.join(X.OUT, 'js', 'frames.js'), 'w', encoding='utf-8').write(js)
    return frames


if __name__ == '__main__':
    main(set(sys.argv[1:]) or None)
